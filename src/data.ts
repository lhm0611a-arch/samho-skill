// 고성능 SplitMix32 의사 난수 생성기 (편향 없는 균등 난수 분포 제공)
function createPRNG(seed: number) {
  let s = (seed ^ 0x9e3779b9) >>> 0;
  return function next() {
    s = (s + 0x6d2b79f5) >>> 0;
    let t = Math.imul(s ^ (s >>> 15), 1 | s);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// MurmurHash3 기반 문자열 해시 함수
function hashString(str: string): number {
  let h = 2166136261 >>> 0;
  for (let i = 0; i < str.length; i++) {
    h = Math.imul(h ^ str.charCodeAt(i), 16777619) >>> 0;
  }
  return h;
}

// 특정 문항 편중 없이 전체 풀(75/75/45개)이 100% 골고루 순환 배정되도록 하는 균등 분배(Balanced Cyclic Deck) 함수
function getBalancedUniformSample(
  pool: QuestionItem[],
  count: number,
  baseSeed: number,
  shuffleIndex: number,
  salt: number
): QuestionItem[] {
  const poolSize = pool.length;
  if (poolSize === 0) return [];
  if (poolSize <= count) {
    const prng = createPRNG((baseSeed + shuffleIndex * 1337 + salt) >>> 0);
    const copy = [...pool];
    for (let i = copy.length - 1; i > 0; i--) {
      const j = Math.floor(prng() * (i + 1));
      [copy[i], copy[j]] = [copy[j], copy[i]];
    }
    return copy;
  }

  // 전체 풀 문항 수에 맞추어 균등하게 순환 이동 (Round-Robin Deck)
  const totalOffset = (shuffleIndex * count) % poolSize;
  const cycleNumber = Math.floor((shuffleIndex * count) / poolSize);

  // 현재 주기(Cycle)에 대한 결정론적 순열 생성
  const cyclePRNG = createPRNG((baseSeed + cycleNumber * 7919 + salt) >>> 0);
  const permuted = [...pool];
  for (let i = permuted.length - 1; i > 0; i--) {
    const j = Math.floor(cyclePRNG() * (i + 1));
    [permuted[i], permuted[j]] = [permuted[j], permuted[i]];
  }

  // 풀 범위를 넘어가는 경우 다음 주기 순열과 자연스럽게 결합하여 100% 비복원 균등 노출 보장
  const result: QuestionItem[] = [];
  for (let i = 0; i < count; i++) {
    const rawIdx = totalOffset + i;
    const wrappedIdx = rawIdx % poolSize;
    if (rawIdx < poolSize) {
      result.push(permuted[wrappedIdx]);
    } else {
      const nextCyclePRNG = createPRNG((baseSeed + (cycleNumber + 1) * 7919 + salt) >>> 0);
      const nextPermuted = [...pool];
      for (let k = nextPermuted.length - 1; k > 0; k--) {
        const j = Math.floor(nextCyclePRNG() * (k + 1));
        [nextPermuted[k], nextPermuted[j]] = [nextPermuted[j], nextPermuted[k]];
      }
      result.push(nextPermuted[wrappedIdx]);
    }
  }

  return result;
}

// Helper: 인원별(수험번호, 이름, E-9 여부) 난이도별 10문항씩 고유 배정 생성 함수 (75/75/45개 원본 풀에서 균등 배정)
export function generateCandidateQuestions(
  candidate: {
    app_no?: string;
    name?: string;
    e9?: string;
  },
  shuffleIndex: number = 0
): {
  basic: QuestionItem[];
  intermediate: QuestionItem[];
  advanced: QuestionItem[];
} {
  const isE9 = candidate?.e9 === 'O' || candidate?.e9 === 'o' || candidate?.e9 === 'Y' || candidate?.e9 === 'y';
  const seedKey = `${candidate?.app_no || ''}_${candidate?.name || ''}`;
  const baseSeed = hashString(seedKey);

  // 1. 초급 10문항 배정 (특정 문항 쏠림 없이 초급 75문항 원본 풀에서 골고루 순환 추출)
  let basicItems: QuestionItem[] = [];
  if (isE9) {
    // E-9 유경험자: 상위 5문항은 E-9 전용 필수 정보 질문(5개 고정), 나머지 5문항은 초급 75문항 풀에서 골고루 순환 추출
    const e9Base = [...E9_DEFAULT_QUESTIONS];
    const sampledBasic = getBalancedUniformSample(QUESTIONS_POOL_BASIC, 5, baseSeed, shuffleIndex, 101);
    basicItems = [...e9Base, ...sampledBasic];
  } else {
    // 일반 응시자: 초급 75문항 원본 풀에서 10문항을 특정 문항 편중 없이 골고루 순환 추출
    basicItems = getBalancedUniformSample(QUESTIONS_POOL_BASIC, 10, baseSeed, shuffleIndex, 101);
  }

  // 2. 중급 10문항 배정 (중급 75문항 원본 풀에서 특정 문항 편중 없이 10문항씩 골고루 순환 추출)
  const intermediateItems = getBalancedUniformSample(QUESTIONS_POOL_INTERMEDIATE, 10, baseSeed, shuffleIndex, 202);

  // 3. 고급 10문항 배정 (고급 45문항 원본 풀에서 특정 문항 편중 없이 10문항씩 골고루 순환 추출)
  const advancedItems = getBalancedUniformSample(QUESTIONS_POOL_ADVANCED, 10, baseSeed, shuffleIndex, 303);

  return {
    basic: basicItems,
    intermediate: intermediateItems,
    advanced: advancedItems
  };
}

